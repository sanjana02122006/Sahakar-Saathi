#!/usr/bin/env node
/**
 * Translates lib/i18n/en.ts into every other supported language via Gemini,
 * and writes lib/i18n/<code>.ts files with the same key structure.
 *
 * Usage: node scripts/generate-translations.mjs
 * Reads GEMINI_API_KEY from .env.local.
 */
import fs from "node:fs";
import path from "node:path";

const envPath = path.join(process.cwd(), ".env.local");
const env = Object.fromEntries(
  fs.readFileSync(envPath, "utf8")
    .split("\n")
    .filter((l) => l.includes("=") && !l.startsWith("#"))
    .map((l) => { const i = l.indexOf("="); return [l.slice(0, i), l.slice(i + 1)]; })
);
const GEMINI_API_KEY = process.env.GEMINI_API_KEY || env.GEMINI_API_KEY;
if (!GEMINI_API_KEY) { console.error("GEMINI_API_KEY not found in .env.local"); process.exit(1); }

const TARGETS = [
  { code: "hi", name: "Hindi" },
  { code: "mr", name: "Marathi" },
  { code: "ta", name: "Tamil" },
  { code: "te", name: "Telugu" },
  { code: "bn", name: "Bengali" },
  { code: "gu", name: "Gujarati" },
  { code: "kn", name: "Kannada" },
  { code: "pa", name: "Punjabi" },
];

// Load en.ts by stripping the TS wrapper and eval'ing the plain object literal.
const enSrc = fs.readFileSync(path.join(process.cwd(), "lib/i18n/en.ts"), "utf8");
const objLiteral = enSrc.slice(enSrc.indexOf("= {") + 2, enSrc.lastIndexOf("} as const"));
// eslint-disable-next-line no-eval
const enDict = eval("(" + objLiteral + "})");

const MODEL = "gemini-3.1-flash-lite";

async function translate(dict, langName) {
  const prompt = `Translate every string VALUE in this JSON object into ${langName}, for a government cooperative-society assistance app aimed at rural users. Keep it simple, natural, and formal-but-warm — not literal machine translation. Preserve any {placeholder} tokens exactly as-is (e.g. "{name}"). Do NOT translate JSON keys. Return ONLY valid JSON with the identical key structure, no markdown fences, no commentary.

${JSON.stringify(dict, null, 2)}`;

  const res = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent?key=${GEMINI_API_KEY}`,
    {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        contents: [{ role: "user", parts: [{ text: prompt }] }],
        generationConfig: { temperature: 0.2, maxOutputTokens: 4000, responseMimeType: "application/json" },
      }),
    }
  );

  if (!res.ok) throw new Error(`${res.status}: ${(await res.text()).slice(0, 300)}`);
  const data = await res.json();
  const text = data?.candidates?.[0]?.content?.parts?.map((p) => p.text).join("") ?? "";
  return JSON.parse(text);
}

function toTsFile(code, dict) {
  return `// Auto-generated by scripts/generate-translations.mjs — do not hand-edit.
// Regenerate with: node scripts/generate-translations.mjs
import type { TranslationDict } from "./en";

const ${code}: TranslationDict = ${JSON.stringify(dict, null, 2)};

export default ${code};
`;
}

console.log(`Translating ${Object.keys(enDict).length} sections into ${TARGETS.length} languages...\n`);

for (const { code, name } of TARGETS) {
  process.stdout.write(`  ${name} (${code}) ... `);
  try {
    const translated = await translate(enDict, name);
    fs.writeFileSync(path.join(process.cwd(), `lib/i18n/${code}.ts`), toTsFile(code, translated));
    console.log("ok");
  } catch (err) {
    console.log("FAILED:", err.message.slice(0, 200));
  }
}

console.log("\nDone. Review lib/i18n/*.ts before shipping to a real demo.");
